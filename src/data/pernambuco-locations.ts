/** Flat list of all cities */
export const allCities = pernambucoLocations.map((l) => l.city);

/** Get neighborhoods for a given city */
export function getNeighborhoods(city: string): string[] {
  return pernambucoLocations.find((l) => l.city === city)?.neighborhoods ?? [];
}

/** Search cities and neighborhoods matching a query */
export function searchLocations(query: string): { city: string; neighborhood?: string }[] {
  const q = query.toLowerCase().trim();
  if (!q) return allCities.map((city) => ({ city }));

  const results: { city: string; neighborhood?: string }[] = [];

  for (const loc of pernambucoLocations) {
    if (loc.city.toLowerCase().includes(q)) {
      results.push({ city: loc.city });
    }
    for (const n of loc.neighborhoods) {
      if (n.toLowerCase().includes(q)) {
        results.push({ city: loc.city, neighborhood: n });
      }
    }
  }

  return results.slice(0, 15);
}
